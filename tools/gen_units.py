#!/usr/bin/env python3
"""Generate config/units.json.

Precedence:
  1. config/tu_inferred.json   probable TUs from tools/infer_units.py, nested under
                               their -G range: tu/g8/00104da8/00101234
  2. -G8 ranges from tu_g.json (one unit per range, big ranges split)
  3. flat address buckets
"""
import csv, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUCKET = int(os.environ.get("UNIT_BUCKET", "0x20000"), 0)

def load_symbols():
    rows = []
    with open(os.path.join(ROOT, "config", "symbols.csv"), newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            rows.append({"addr": int(r["address"], 16), "size": int(r["size"]), "name": r["name"]})
    return rows

def load_matched():
    p = os.path.join(ROOT, "config", "overrides.json")
    with open(p, encoding="utf-8") as f:
        data = json.load(f)
    return {int(fn["addr"], 16) for fn in data.get("functions", []) if fn.get("status") == "matched"}

def load_ranges():
    p = os.path.join(ROOT, "config", "tu_g.json")
    if not os.path.exists(p):
        return []
    with open(p, encoding="utf-8") as f:
        data = json.load(f)
    return [(int(r["start"], 16), int(r["end"], 16), r.get("g", 8)) for r in data.get("ranges", [])]

def load_inferred():
    p = os.path.join(ROOT, "config", "tu_inferred.json")
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as f:
        data = json.load(f)
    return data.get("groups") or None

def g_label(addr, ranges):
    for a, b, g in ranges:
        if a <= addr < b:
            return "g%d" % g
    return "g0"

def main():
    syms = load_symbols()
    matched = load_matched()
    ranges = load_ranges()
    inferred = load_inferred()

    units = []
    if inferred:
        for g in inferred:
            units.append({
                "name": "tu/%s/%08x" % (g_label(int(g["start"]), ranges), int(g["start"])),
                "start": int(g["start"]),
                "end": int(g["end"]),
                "functions": g.get("functions", 0),
                "addrs": g.get("addrs", []),
                "confidence": g.get("confidence", "low"),
            })
    else:
        for a, b, gg in ranges:
            fs = [s for s in syms if a <= s["addr"] < b]
            if not fs:
                continue
            span = BUCKET
            n = max(1, (b - a + span - 1) // span)
            for i in range(n):
                s0 = a + i * span
                units.append({"name": "game/g%d/%08x" % (gg, s0),
                              "start": s0, "end": min(b, s0 + span),
                              "functions": len([x for x in fs if s0 <= x["addr"] < min(b, s0 + span)]),
                              "confidence": "medium"})

    out = {
        "note": "generated by tools/gen_units.py",
        "source": "tu_inferred" if inferred else "tu_g",
        "units": units,
    }
    dest = os.path.join(ROOT, "config", "units.json")
    with open(dest, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1)
    print("source=%s units=%d functions=%d" % (out["source"], len(units), sum(u["functions"] for u in units)))

if __name__ == "__main__":
    main()
