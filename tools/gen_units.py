#!/usr/bin/env python3
"""Generate config/units.json from rules that evolve with project progress.

Rules (recomputed on every `make progress`):
  1. A -G8 range whose functions are 100% matched collapses into game/done/<start>.
  2. Other ranges are split so no unit exceeds maxspan(), which shrinks as the
     match ratio grows: <5% 128 KB, <30% 64 KB, <70% 32 KB, else 16 KB.
  3. Addresses outside any -G8 range are bucketed with the same maxspan.
"""
import csv, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def load_symbols():
    rows = []
    with open(os.path.join(ROOT, "config", "symbols.csv"), newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            rows.append({"addr": int(r["address"], 16), "size": int(r["size"]), "name": r["name"]})
    return rows

def load_matched():
    p = os.path.join(ROOT, "config", "overrides.json")
    with open(p, encoding="utf-8") as f:
        data = json.load(f)
    return {int(fn["addr"], 16) for fn in data.get("functions", []) if fn.get("status") == "matched"}

def load_ranges():
    p = os.path.join(ROOT, "config", "tu_g.json")
    if not os.path.exists(p):
        return []
    with open(p, encoding="utf-8") as f:
        data = json.load(f)
    out = []
    for r in data.get("ranges", []):
        out.append((int(r["start"], 16), int(r["end"], 16), r.get("g", 8)))
    return out

def maxspan_for(ratio):
    if ratio < 0.05:
        return 0x20000
    if ratio < 0.30:
        return 0x10000
    if ratio < 0.70:
        return 0x8000
    return 0x4000

def main():
    syms = load_symbols()
    matched = load_matched()
    ranges = load_ranges()
    total = sum(s["size"] for s in syms)
    mbytes = sum(s["size"] for s in syms if s["addr"] in matched)
    ratio = mbytes / total if total else 0.0
    span = maxspan_for(ratio)

    units = []
    covered = []

    def add(name, a, b):
        fs = [s for s in syms if a <= s["addr"] < b]
        if not fs:
            return
        units.append({"name": name, "start": a, "end": b, "functions": len(fs)})

    for a, b, g in ranges:
        fs = [s for s in syms if a <= s["addr"] < b]
        if not fs:
            continue
        if all(s["addr"] in matched for s in fs):
            add("game/done/%08x" % a, a, b)
        else:
            n = max(1, (b - a + span - 1) // span)
            for i in range(n):
                s0 = a + i * span
                e0 = min(b, s0 + span)
                add("game/g%d/%08x" % (g, s0), s0, e0)
        covered.append((a, b))

    # addresses outside known -G8 ranges
    starts = sorted(s["addr"] for s in syms)
    if starts:
        lo, hi = starts[0], max(s["addr"] + s["size"] for s in syms)
        holes = []
        cur = lo
        for a, b in sorted(covered):
            if a > cur:
                holes.append((cur, a))
            cur = max(cur, b)
        if cur < hi:
            holes.append((cur, hi))
        for a, b in holes:
            b = min(b, hi)
            n = max(1, (b - a + span - 1) // span)
            for i in range(n):
                s0 = a + i * span
                e0 = min(b, s0 + span)
                add("game/g0/%08x" % s0, s0, e0)

    units.sort(key=lambda u: u["start"])
    out = {
        "note": "generated by tools/gen_units.py; rules evolve with match ratio",
        "match_ratio": round(ratio * 100, 4),
        "maxspan": span,
        "units": units,
    }
    dest = os.path.join(ROOT, "config", "units.json")
    with open(dest, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1)
    print("ratio %.4f%% -> maxspan 0x%x, %d units" % (ratio * 100, span, len(units)))
    for u in units:
        print("  %-24s %5d funcs" % (u["name"], u["functions"]))

if __name__ == "__main__":
    main()
